import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';

await rm(new URL('../dist/', import.meta.url), { force: true, recursive: true });
await mkdir(new URL('../dist/', import.meta.url), { recursive: true });
await Promise.all([
  cp(new URL('../src/index.css', import.meta.url), new URL('../dist/index.css', import.meta.url)),
  cp(new URL('../src/base.css', import.meta.url), new URL('../dist/base.css', import.meta.url)),
  cp(new URL('../src/typography.css', import.meta.url), new URL('../dist/typography.css', import.meta.url)),
  cp(new URL('../src/v016.css', import.meta.url), new URL('../dist/v016.css', import.meta.url)),
  cp(new URL('../src/v016-monochrome.css', import.meta.url), new URL('../dist/v016-monochrome.css', import.meta.url)),
]);

// JS geometry companions are generated from the effective v016 theme so a
// panel header or grid size can never drift between CSS and layout math.
const GEOMETRY_TOKENS = new Map([
  ['--size-header-panel', 'SIZE_HEADER_PANEL_PX'],
]);
const v016 = await readFile(new URL('../src/v016.css', import.meta.url), 'utf8');
const declarations = [];
for (const [token, exportName] of GEOMETRY_TOKENS) {
  const match = v016.match(new RegExp(`${token}:\\s*(\\d+(?:\\.\\d+)?)px\\s*;`));
  if (!match) throw new Error(`${token} must declare a px value in v016.css`);
  declarations.push(`export const ${exportName} = ${match[1]};`);
}
const geometryModule = `// Generated by scripts/build.mjs from src/v016.css. Do not edit.\n${declarations.join('\n')}\n`;
const geometryTypes = declarations
  .map((line) => line.replace('export const', 'export declare const'))
  .join('\n');
await Promise.all([
  writeFile(new URL('../dist/geometry.mjs', import.meta.url), geometryModule),
  writeFile(new URL('../dist/geometry.d.ts', import.meta.url), `${geometryTypes}\n`),
]);
