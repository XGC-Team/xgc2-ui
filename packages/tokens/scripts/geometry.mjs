// Generated geometry companions are derived from the effective v016 theme so a
// panel header, control row or spacing value can never drift between CSS and
// layout math. Only generic geometry is exported here; product-specific
// composite floors stay in the consuming layout owner.
export const GEOMETRY_TOKENS = new Map([
  ['--size-header-panel', 'SIZE_HEADER_PANEL_PX'],
  ['--size-control-default', 'SIZE_CONTROL_DEFAULT_PX'],
  ['--size-control-compact', 'SIZE_CONTROL_COMPACT_PX'],
  ['--space-sm', 'SPACE_SM_PX'],
  ['--space-lg', 'SPACE_LG_PX'],
  ['--stroke-thin', 'STROKE_THIN_PX'],
]);

export function buildGeometry(css) {
  const declarations = [];
  for (const [token, exportName] of GEOMETRY_TOKENS) {
    const match = String(css).match(new RegExp(`${token}:\\s*(\\d+(?:\\.\\d+)?)px\\s*;`));
    if (!match) throw new Error(`${token} must declare a px value in v016.css`);
    declarations.push(`export const ${exportName} = ${match[1]};`);
  }
  const module = `// Generated by scripts/build.mjs from src/v016.css. Do not edit.\n${declarations.join('\n')}\n`;
  const types = declarations
    .map((line) => line.replace('export const', 'export declare const'))
    .join('\n');
  return { module, types };
}
