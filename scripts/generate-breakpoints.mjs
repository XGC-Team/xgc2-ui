import { readdir, readFile, writeFile } from 'node:fs/promises';
import { extname, join } from 'node:path';

const root = new URL('../', import.meta.url);
const breakpoints = JSON.parse(await readFile(new URL('packages/tokens/src/breakpoints.json', root), 'utf8'));
const names = ['compact', 'mobile'];

for (const name of names) {
  if (!Number.isSafeInteger(breakpoints[name]) || breakpoints[name] <= 0) {
    throw new Error(`Breakpoint ${name} must be a positive integer`);
  }
}
if (breakpoints.mobile >= breakpoints.compact) {
  throw new Error('The mobile breakpoint must be narrower than the compact breakpoint');
}
if (Object.keys(breakpoints).sort().join(',') !== [...names].sort().join(',')) {
  throw new Error('breakpoints.json must contain only the finite compact and mobile contract');
}

const generatedHeader = '/* Generated by scripts/generate-breakpoints.mjs from packages/tokens/src/breakpoints.json. */';
const artifacts = [
  {
    output: 'packages/react/src/hooks/breakpoints.generated.ts',
    content: `${generatedHeader}\nexport const XGC_BREAKPOINTS = ${JSON.stringify(breakpoints, null, 2)} as const;\n`,
  },
  ...await Promise.all([
    ['packages/react/src/responsive.template.css', 'packages/react/src/responsive.generated.css'],
    ['apps/gallery/src/responsive.template.css', 'apps/gallery/src/responsive.generated.css'],
  ].map(async ([template, output]) => {
    let content = await readFile(new URL(template, root), 'utf8');
    for (const name of names) content = content.replaceAll(`{{${name}}}`, String(breakpoints[name]));
    if (/{{[^}]+}}/.test(content)) throw new Error(`Unknown breakpoint placeholder in ${template}`);
    return { output, content: `${generatedHeader}\n${content}` };
  })),
];

const check = process.argv.includes('--check');
const stale = [];
for (const artifact of artifacts) {
  const url = new URL(artifact.output, root);
  if (check) {
    const current = await readFile(url, 'utf8').catch(() => '');
    if (current !== artifact.content) stale.push(artifact.output);
  } else {
    await writeFile(url, artifact.content);
  }
}
if (stale.length) throw new Error(`Generated breakpoint artifacts are stale: ${stale.join(', ')}`);

async function collectSources(directory) {
  const entries = await readdir(new URL(`${directory}/`, root), { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      if (!['dist', 'node_modules', 'storybook-static'].includes(entry.name)) files.push(...await collectSources(path));
    } else if (['.css', '.ts', '.tsx'].includes(extname(entry.name))) {
      files.push(path);
    }
  }
  return files;
}

const responsiveAuthorityViolations = [];
for (const file of (await Promise.all(['packages', 'apps'].map(collectSources))).flat()) {
  const source = await readFile(new URL(file, root), 'utf8');
  if (/--breakpoint-(?:compact|mobile)\s*:/.test(source)) {
    responsiveAuthorityViolations.push(`${file}: CSS custom property cannot define a media-query breakpoint`);
  }
  if (!file.endsWith('.generated.css')) {
    for (const name of names) {
      if (new RegExp(`\\(max-width:\\s*${breakpoints[name]}px\\)`).test(source)) {
        responsiveAuthorityViolations.push(`${file}: hard-coded ${name} breakpoint`);
      }
    }
  }
  if (!file.endsWith('breakpoints.generated.ts') && /XGC_BREAKPOINTS\s*=/.test(source)) {
    responsiveAuthorityViolations.push(`${file}: parallel TypeScript breakpoint authority`);
  }
}
if (responsiveAuthorityViolations.length) {
  throw new Error(`Responsive breakpoint authority drifted:\n${responsiveAuthorityViolations.join('\n')}`);
}
