export function localizeCameraValidationIssue(
  t: LocalizedText,
  issue: CameraValidationIssue,
): string {
  switch (issue.code) {
    case 'camera-sources-missing': return t('Camera source configuration is missing.');
    case 'camera-sources-invalid-json': return t('Camera source configuration is not valid JSON.');
    case 'camera-sources-not-list': return t('Camera source configuration must be a list.');
    case 'camera-source-not-object':
      return t('Camera source {index} must be an object.', issue.args);
    case 'camera-source-invalid-field-types':
      return t('Camera source {index} has invalid field types.', issue.args);
    case 'camera-sources-empty': return t('Add at least one camera source.');
    case 'camera-sources-too-many':
      return t('A multi-camera monitor supports at most {maximum} sources.', issue.args);
    case 'camera-source-invalid-id': return t('{label} has an invalid stable ID.', issue.args);
    case 'camera-source-duplicate-id': return t('Camera source ID "{id}" is duplicated.', issue.args);
    case 'camera-source-name-required': return t('Camera source {index} requires a display name.', issue.args);
    case 'camera-source-runtime-invalid':
      return `${issue.args.label}：${localizeCameraValidationIssue(t,issue.args.issue)}`;
    case 'camera-sources-none-enabled': return t('Enable at least one camera source.');
    case 'camera-option-unsupported': return t('Unsupported {key} value.', issue.args);
    case 'camera-show-metadata-invalid': return t('Show metadata must be a boolean.');
    case 'media-edge-required': return t('Set the camera Media Edge URL in the panel settings.');
    case 'media-edge-url-invalid': return t('Media Edge URL must be an absolute HTTP or HTTPS origin.');
    case 'media-source-required': return t('Set the stable Media Edge source ID in the panel settings.');
    case 'media-source-id-invalid':
      return t('Media source must be a stable ID containing only letters, numbers, dots, underscores, and hyphens.');
    case 'media-binding-id-invalid': return t('Camera media workflow binding must be a stable binding ID.');
    case 'camera-image-fit-invalid': return t('Camera image fit must be contain or cover.');
    case 'camera-reconnect-policy-invalid': return t('Camera reconnect policy must be automatic or manual.');
    case 'camera-boolean-option-invalid': return t('{field} must be a boolean.', issue.args);
    case 'managed-direct-media-edge-http-required':
      return t('Managed direct Media Edge URL must use HTTP; place HTTPS termination in front of a separately configured Edge.');
    case 'managed-intrinsic-media-edge-http-required': return t('Managed intrinsic Media Edge URL must use HTTP.');
    case 'media-edge-explicit-port-required': return t('Media Edge URL must include its explicit control port.');
    case 'media-edge-port-invalid': return t('Media Edge URL contains an invalid port.');
    case 'world-camera-source-id-invalid': return t('World camera source must be a stable Media Edge source ID.');
    case 'calibration-camera-source-id-invalid':
      return t('Calibration camera source must be a stable Media Edge source ID.');
    case 'world-coordinate-out-of-range':
      return t('World {axis} must be finite and within ±100000 metres.', issue.args);
    case 'world-angle-out-of-range':
      return t('{angle} must be between -360 and 360 degrees.', { angle:t(issue.args.angle) });
  }
}

/** Translate stable client/model errors while preserving unknown server diagnostics verbatim. */
export function localizeCameraMessage(t: LocalizedText, message: string): string {
  if (!message) return '';
  return t(message);
}
