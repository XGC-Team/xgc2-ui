// Keep the original family stylesheet confined to Marker and its portaled menu.
import fs from 'node:fs'
import postcss from 'postcss'
const source=postcss.parse(fs.readFileSync('node_modules/@xgc2/ui-react/dist/styles.css','utf8'))
const roots=':is(.dev-annotation-toolbar, .dev-annotation-layer, .xgc-select-menu[aria-label="Herdr pane"])'
const output=postcss.root()
source.each(node=>{
 if(node.type==='rule' && node.selector.includes(':root')){
  const copy=node.clone()
  copy.selector=copy.selectors.map(s=>s.replaceAll(':root[data-skin=light]',`html:not(.dark) ${roots}`).replaceAll(':root[data-skin=dark]',`html.dark ${roots}`).replaceAll(':root',roots)).join(',')
  output.append(copy)
 }else{
  const copy=node.clone()
  const includeRoot=rule=>{rule.selector=rule.selectors.map(s=>`:scope:is(${s}), ${s}`).join(',')}
  if(copy.type==='rule') includeRoot(copy)
  else if(copy.type==='atrule' && !copy.name.includes('keyframes')) copy.walkRules(includeRoot)
  const scope=postcss.atRule({name:'scope',params:`(${roots})`});scope.append(copy);output.append(scope)
 }
})
fs.writeFileSync('src/devtools/mark-prompt/family-scoped.css','/* Generated by scripts/prepare-marker-styles.mjs from @xgc2/ui-react 0.16.10. */\n'+output.toString())
